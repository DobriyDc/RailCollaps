// ============================================================================
//  The leaderboard function in one file (server/leaderboard/dist/worker.js)
// ----------------------------------------------------------------------------
//  node tools/build-worker.mjs
//
//  The function replays a run with the game's own rules, so it has no copy of them:
//  js/CollapseRules.js goes in whole, of js/Constants.js — the lines of the constants
//  that the rules and the function name. wrangler runs this before every deploy
//  (server/leaderboard/wrangler.toml); dist/ is not in the repository.
// ============================================================================
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const read = rel => fs.readFileSync(path.join(ROOT, rel), 'utf8');

export function workerSource() {
  const rules = read('js/CollapseRules.js'), handler = read('server/leaderboard/src/index.js');
  const named = new Set((rules + handler).match(/\b(?:COLLAPSE|LEADERBOARD)_[A-Z0-9_]+\b/g));
  const constants = read('js/Constants.js').split(/\r?\n/).filter(line => {
    const m = /^const ([A-Z0-9_]+) = /.exec(line);
    return m && named.has(m[1]);
  });
  for (const name of named) {
    const required = name.startsWith('LEADERBOARD_') || name === 'COLLAPSE_RULES_VERSION';
    if (required && !constants.some(line => line.startsWith('const ' + name + ' = '))) throw new Error('нет константы ' + name + ' в js/Constants.js');
  }
  return ['// Generated by tools/build-worker.mjs: do not edit.', ...constants, '', rules, handler].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === url.fileURLToPath(import.meta.url)) {
  const out = path.join(ROOT, 'server', 'leaderboard', 'dist', 'worker.js');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, workerSource());
  console.log('  ' + path.relative(ROOT, out) + ' — ' + fs.statSync(out).size + ' байт');
}
